import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const DEFAULT_SECRETS_DIR = path.join(ROOT_DIR, '.license-secrets');
const DEFAULT_PRIVATE_KEY_PATH = path.join(DEFAULT_SECRETS_DIR, 'omnigeo-private.pem');
const DEFAULT_PUBLIC_KEY_MODULE_PATH = path.join(ROOT_DIR, 'electron', 'licensePublicKey.cjs');
const LICENSE_PREFIX = 'OMNIGEO-LIC-V1';

function toBase64Url(bufOrStr) {
  const buf = Buffer.isBuffer(bufOrStr) ? bufOrStr : Buffer.from(bufOrStr, 'utf8');
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/g, '');
}

function fromBase64Url(str) {
  const norm = str.replace(/-/g, '+').replace(/_/g, '/');
  const pad = (4 - (norm.length % 4)) % 4;
  return Buffer.from(norm + '='.repeat(pad), 'base64');
}

function parseArgs(argv) {
  const [command, ...rest] = argv;
  const flags = {};
  for (let i = 0; i < rest.length; i++) {
    const tok = rest[i];
    if (tok.startsWith('--')) {
      const key = tok.slice(2);
      const next = rest[i + 1];
      if (!next || next.startsWith('--')) {
        flags[key] = true;
      } else {
        flags[key] = next;
        i++;
      }
    }
  }
  return {command, flags};
}

function printHelp() {
  console.log(`
OmniGeo Offline Ed25519 License CLI

Commands:
  init-keys [--force] [--private-key <path>] [--public-module <path>]
      Generates a new Ed25519 private/public keypair.
      Stores private key in .license-secrets/omnigeo-private.pem (gitignored)
      and embeds the public key in electron/licensePublicKey.cjs.

  issue --tier <trial|annual|lifetime> --machine <OMNI-XXXX-XXXX-XXXX | *> --customer "<Name>"
        [--days <N>] [--email "<email>"] [--out <file.omnigeo-lic>] [--private-key <path>]
      Signs an offline license bound to a specific desktop Machine ID (or "*" for your master owner key).

  verify --key "<OMNIGEO-LIC-V1...>" [--machine <OMNI-XXXX-XXXX-XXXX>] [--public-module <path>]
      Verifies a license key signature, machine binding, and expiration date.
`);
}

function initKeys(flags) {
  const privateKeyPath = flags['private-key'] ? path.resolve(flags['private-key']) : DEFAULT_PRIVATE_KEY_PATH;
  const publicModulePath = flags['public-module'] ? path.resolve(flags['public-module']) : DEFAULT_PUBLIC_KEY_MODULE_PATH;

  if (fs.existsSync(privateKeyPath) && !flags.force) {
    console.error(`Refusing to overwrite existing private key at ${privateKeyPath}.`);
    console.error('Pass --force if you really want to rotate keys (existing issued licenses will stop validating!).');
    process.exit(1);
  }

  const {publicKey, privateKey} = crypto.generateKeyPairSync('ed25519', {
    publicKeyEncoding: {type: 'spki', format: 'pem'},
    privateKeyEncoding: {type: 'pkcs8', format: 'pem'},
  });

  fs.mkdirSync(path.dirname(privateKeyPath), {recursive: true});
  fs.writeFileSync(privateKeyPath, privateKey, {mode: 0o600});

  const moduleSource = `/**
 * @license
 * SPDX-License-Identifier: Apache-2.0
 *
 * Auto-generated by scripts/license-cli.mjs init-keys on ${new Date().toISOString()}.
 * Safe to ship inside the Electron desktop bundle.
 */

const LICENSE_PUBLIC_KEY_PEM = \`${publicKey.trim()}\`;

const IS_PRODUCTION_KEY_CONFIGURED = true;

module.exports = {
  LICENSE_PUBLIC_KEY_PEM,
  IS_PRODUCTION_KEY_CONFIGURED,
};
`;

  fs.mkdirSync(path.dirname(publicModulePath), {recursive: true});
  fs.writeFileSync(publicModulePath, moduleSource, 'utf8');

  console.log('Ed25519 keypair generated successfully.');
  console.log(`  Private key (KEEP SECRET & BACK UP SAFELY): ${privateKeyPath}`);
  console.log(`  Embedded public key module updated:         ${publicModulePath}`);
}

function issueLicense(flags) {
  const tier = String(flags.tier || '').toLowerCase();
  if (!['trial', 'annual', 'lifetime'].includes(tier)) {
    console.error('Invalid or missing --tier. Must be one of: trial, annual, lifetime');
    process.exit(1);
  }

  const machineId = String(flags.machine || '').trim().toUpperCase();
  if (!machineId || (machineId !== '*' && !/^OMNI-[A-F0-9]{4}-[A-F0-9]{4}-[A-F0-9]{4}$/.test(machineId))) {
    console.error('Invalid or missing --machine. Expected OMNI-XXXX-XXXX-XXXX or "*" for personal master key.');
    process.exit(1);
  }

  const customer = String(flags.customer || '').trim();
  if (!customer) {
    console.error('Missing --customer "<Customer or Organization Name>"');
    process.exit(1);
  }

  const privateKeyPath = flags['private-key'] ? path.resolve(flags['private-key']) : DEFAULT_PRIVATE_KEY_PATH;
  if (!fs.existsSync(privateKeyPath)) {
    console.error(`Private key not found at ${privateKeyPath}. Run "npm run license:init-keys" first.`);
    process.exit(1);
  }

  const now = new Date();
  let expiresAt = null;
  if (tier === 'trial') {
    const days = Math.max(1, Number(flags.days || 14));
    expiresAt = new Date(now.getTime() + days * 24 * 60 * 60 * 1000).toISOString();
  } else if (tier === 'annual') {
    const days = Math.max(1, Number(flags.days || 365));
    expiresAt = new Date(now.getTime() + days * 24 * 60 * 60 * 1000).toISOString();
  }

  const shortRand = crypto.randomBytes(3).toString('hex').toUpperCase();
  const licenseId = `LIC-${now.getUTCFullYear()}-${shortRand}`;

  const payload = {
    v: 1,
    licenseId,
    tier,
    customer,
    ...(flags.email ? {email: String(flags.email).trim()} : {}),
    machineId,
    issuedAt: now.toISOString(),
    expiresAt,
  };

  const payloadB64 = toBase64Url(JSON.stringify(payload));
  const privateKeyPem = fs.readFileSync(privateKeyPath, 'utf8');
  const signature = crypto.sign(null, Buffer.from(payloadB64, 'utf8'), privateKeyPem);
  const licenseKey = `${LICENSE_PREFIX}.${payloadB64}.${toBase64Url(signature)}`;

  console.log('\n============================================================');
  console.log('OMNIGEO OFFLINE LICENSE ISSUED');
  console.log('============================================================');
  console.log(`License ID : ${licenseId}`);
  console.log(`Tier       : ${tier.toUpperCase()}${expiresAt ? '' : ' (INDEFINITE)'}`);
  console.log(`Customer   : ${customer}`);
  console.log(`Machine ID : ${machineId === '*' ? '* (MASTER — ANY DESKTOP)' : machineId}`);
  console.log(`Issued At  : ${payload.issuedAt}`);
  console.log(`Expires At : ${expiresAt || 'Never'}`);
  console.log('------------------------------------------------------------');
  console.log(licenseKey);
  console.log('============================================================\n');

  if (flags.out) {
    const outPath = path.resolve(flags.out);
    const fileContent = JSON.stringify(
      {
        product: 'OmniGeo Desktop',
        licenseId,
        tier,
        customer,
        machineId,
        issuedAt: payload.issuedAt,
        expiresAt,
        licenseKey,
      },
      null,
      2
    );
    fs.writeFileSync(outPath, fileContent, 'utf8');
    console.log(`Saved license file to: ${outPath}`);
  }
}

function verifyLicense(flags) {
  const rawKey = String(flags.key || '').trim();
  if (!rawKey) {
    console.error('Missing --key "OMNIGEO-LIC-V1...."');
    process.exit(1);
  }

  const publicModulePath = flags['public-module'] ? path.resolve(flags['public-module']) : DEFAULT_PUBLIC_KEY_MODULE_PATH;
  const source = fs.readFileSync(publicModulePath, 'utf8');
  const pemMatch = source.match(/-----BEGIN PUBLIC KEY-----[\s\S]+?-----END PUBLIC KEY-----/);
  if (!pemMatch) {
    console.error(`Could not read public key PEM from ${publicModulePath}`);
    process.exit(1);
  }

  const parts = rawKey.replace(/\s+/g, '').split('.');
  if (parts.length !== 3 || parts[0] !== LICENSE_PREFIX) {
    console.error('INVALID: Malformed license key format.');
    process.exit(1);
  }

  const [, payloadB64, sigB64] = parts;
  const ok = crypto.verify(
    null,
    Buffer.from(payloadB64, 'utf8'),
    pemMatch[0],
    fromBase64Url(sigB64)
  );

  if (!ok) {
    console.error('INVALID: Cryptographic signature verification FAILED.');
    process.exit(1);
  }

  const payload = JSON.parse(fromBase64Url(payloadB64).toString('utf8'));
  const targetMachine = flags.machine ? String(flags.machine).trim().toUpperCase() : null;
  if (targetMachine && payload.machineId !== '*' && payload.machineId !== targetMachine) {
    console.error(`INVALID: Machine mismatch (key is for ${payload.machineId}, checked against ${targetMachine}).`);
    process.exit(1);
  }

  if (payload.expiresAt && Date.now() > Date.parse(payload.expiresAt)) {
    console.error(`EXPIRED: License expired on ${payload.expiresAt}.`);
    process.exit(1);
  }

  console.log('VALID LICENSE:');
  console.log(JSON.stringify(payload, null, 2));
}

const {command, flags} = parseArgs(process.argv.slice(2));
if (command === 'init-keys') {
  initKeys(flags);
} else if (command === 'issue') {
  issueLicense(flags);
} else if (command === 'verify') {
  verifyLicense(flags);
} else {
  printHelp();
}
